def build_glossary() -> dict:
    entries = [
        {
            "term": t,
            "expansion": e,
            "category": c,
            "definition": d,
            "where": w,
            "search": f"{t} {e} {d} {w}".lower(),
        }
        for t, e, c, d, w in TERMS
    ]
    by_category = {
        cat: [e for e in entries if e["category"] == cat] for cat in CATEGORIES
    }
    return {
        "count": len(entries),
        "categories": [
            {"name": cat, "count": len(by_category[cat]), "entries": by_category[cat]}
            for cat in CATEGORIES
            if by_category[cat]
        ],
        "entries": entries,
        "note": (
            "Abbreviations were harvested by scanning every source file in the repository for "
            "capitalised tokens, then defined in context. tests/test_glossary.py re-runs that scan "
            "and fails if a term used in the code is missing here."
        ),
    }
